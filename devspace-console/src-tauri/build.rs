use std::{env, fs, path::PathBuf};

const WINDOWS_ICON: &[u8] = &[
    0x00, 0x00, 0x01, 0x00, 0x01, 0x00,
    0x01, 0x01, 0x00, 0x00, 0x01, 0x00, 0x20, 0x00, 0x30, 0x00, 0x00, 0x00, 0x16, 0x00, 0x00, 0x00,
    0x28, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x02, 0x00, 0x00, 0x00,
    0x01, 0x00, 0x20, 0x00, 0x00, 0x00, 0x00, 0x00, 0x04, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0xea, 0xa5, 0x34, 0xff, 0x00, 0x00, 0x00, 0x00,
];

fn main() {
    let icon_path = PathBuf::from(env::var_os("OUT_DIR").expect("OUT_DIR is required"))
        .join("webmcp-console.ico");
    fs::write(&icon_path, WINDOWS_ICON).expect("failed to write temporary Windows icon");

    let windows = tauri_build::WindowsAttributes::new().window_icon_path(&icon_path);
    let attributes = tauri_build::Attributes::new().windows_attributes(windows);
    tauri_build::try_build(attributes).expect("failed to run Tauri build helpers");
}
